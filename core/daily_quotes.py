FRASI_PER_MESE_JSON = json.dumps(FRASI_PER_MESE, ensure_ascii=False)


def get_daily_quote_info(target_date=None):
    """Restituisce data formattata in italiano e frase positiva del giorno secondo il calendario."""
    if target_date is None:
        target_date = timezone.localtime(timezone.now()).date()

    mese = target_date.month
    giorno = target_date.day
    anno = target_date.year
    giorno_settimana = GIORNI_SETTIMANA_IT[target_date.weekday()]
    nome_mese = MESI_IT[mese]

    frasi_mese = FRASI_PER_MESE.get(mese, {})
    frase = frasi_mese.get(giorno) or frasi_mese.get(max(frasi_mese.keys(), default=1), "")

    data_estesa = f"{giorno_settimana} {giorno} {nome_mese} {anno}"
    data_breve = f"{giorno} {nome_mese} {anno}"

    return {
        "date": target_date,
        "date_formatted": data_estesa,
        "date_short": data_breve,
        "day": giorno,
        "month": mese,
        "month_name": nome_mese,
        "year": anno,
        "weekday_name": giorno_settimana,
        "quote": frase,
        "quotes_json": FRASI_PER_MESE_JSON,
    }
